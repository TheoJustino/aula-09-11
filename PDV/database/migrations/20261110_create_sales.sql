CREATE TABLE vendas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT REFERENCES clientes(id) ON DELETE SET NULL,
    data_venda TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    valor_total NUMERIC(14, 2) NOT NULL CHECK (valor_total >= 0),
    forma_pagamento VARCHAR(20) NOT NULL
        CHECK (forma_pagamento IN ('dinheiro', 'pix', 'cartao'))
);

CREATE TABLE itens_venda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venda_id BIGINT NOT NULL REFERENCES vendas(id) ON DELETE CASCADE,
    produto_id INTEGER NOT NULL REFERENCES produtos(id) ON DELETE RESTRICT,
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    preco_unitario NUMERIC(14, 2) NOT NULL CHECK (preco_unitario >= 0),
    subtotal NUMERIC(14, 2) NOT NULL
        CHECK (subtotal >= 0 AND subtotal = quantidade * preco_unitario)
);

CREATE INDEX itens_venda_venda_id_idx ON itens_venda (venda_id);